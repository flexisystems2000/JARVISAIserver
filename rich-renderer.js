// JARVIS native rich-message bridge.
// Uses Innovators Baileys' verified message composer, but sends through
// the existing @musteqeem/baileys socket. No second WhatsApp connection.
'use strict';

const crypto = require('crypto');
const {
  generateRichMessageContent,
  tokenizeCode
} = require('@innovatorssoft/baileys/lib/Utils/message-composer');

const TYPE = { TEXT: 2, TABLE: 4, CODE: 5 };

function parseMarkdownBlocks(markdown) {
  const lines = String(markdown || '').replace(/\r\n?/g, '\n').split('\n');
  const blocks = [];
  let text = [];
  const flushText = () => {
    const value = text.join('\n').trim();
    if (value) blocks.push({ messageType: TYPE.TEXT, messageText: value });
    text = [];
  };

  for (let i = 0; i < lines.length;) {
    const fence = lines[i].match(/^\s*```([\w.+-]*)\s*$/);
    if (fence) {
      flushText();
      const language = (fence[1] || 'text').toLowerCase();
      const code = [];
      i++;
      while (i < lines.length && !/^\s*```\s*$/.test(lines[i])) code.push(lines[i++]);
      if (i < lines.length) i++;
      const codeText = code.join('\n');
      blocks.push({
        messageType: TYPE.CODE,
        codeMetadata: {
          codeLanguage: language,
          codeBlocks: tokenizeCode(codeText, language)
        }
      });
      continue;
    }

    // GitHub-style Markdown table: header row, separator row, data rows.
    if (i + 1 < lines.length && /^\s*\|?.+\|.+\|?\s*$/.test(lines[i]) &&
        /^\s*\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)+\|?\s*$/.test(lines[i + 1])) {
      flushText();
      const splitRow = line => line.trim().replace(/^\|/, '').replace(/\|$/, '')
        .split('|').map(cell => cell.trim());
      const headers = splitRow(lines[i]);
      i += 2;
      const rows = [];
      while (i < lines.length && lines[i].includes('|') && lines[i].trim()) rows.push(splitRow(lines[i++]));
      const width = headers.length;
      blocks.push({
        messageType: TYPE.TABLE,
        tableMetadata: {
          title: '',
          rows: [
            { items: headers, isHeading: true },
            ...rows.map(row => ({ items: Array.from({length: width}, (_, n) => row[n] || '') }))
          ]
        }
      });
      continue;
    }

    if (!lines[i].trim()) {
      flushText();
      i++;
      continue;
    }
    text.push(lines[i++]);
  }
  flushText();
  return blocks;
}

async function sendRichReply(sock, jid, markdown, quotedMessage = null) {
  if (!sock || typeof sock.relayMessage !== 'function') {
    throw new Error('The connected Baileys socket does not expose relayMessage().');
  }
  const submessages = parseMarkdownBlocks(markdown);
  if (!submessages.length) return null;

  const { message, messageId } = generateRichMessageContent(
    submessages,
    quotedMessage,
    { useMarkdown: true, botJid: sock.user?.id }
  );

  // relayMessage sends the exact botForwardedMessage/richResponseMessage
  // envelope generated by Innovators' v7.4.9 composer through Jarvis' socket.
  await sock.sendPresenceUpdate?.('composing', jid);
  try {
    const result = await sock.relayMessage(jid, message, { messageId });
    return result || { key: { id: messageId } };
  } finally {
    await sock.sendPresenceUpdate?.('paused', jid).catch?.(() => {});
  }
}

module.exports = { parseMarkdownBlocks, sendRichReply };
